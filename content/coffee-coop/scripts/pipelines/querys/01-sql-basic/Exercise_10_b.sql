--View only the settlements with a status of "pending," ordered by net value from highest to lowest

SELECT
    T1.settlement_id AS settlement,
    T1.delivery_id AS delivery,
    T1.net_amount AS net_cop,
    T1.status AS status
FROM
    pay.settlements AS T1
WHERE
    T1.settlement_id LIKE '%20260930%' AND T1.status = 'pending'
ORDER BY
    T1.net_amount DESC;

